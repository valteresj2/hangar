// Data for Configurações → Sobre: the Agent SDK / Claude Code versions and the third-party notices.
import { app } from 'electron'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import noticesPath from '../../../../resources/third-party-notices.json?asset'
import type { ThirdPartyNotice } from '../../../shared/features/settings'

/** Version of the Agent SDK and of the Claude Code it bundles (from the SDK's package.json). */
export function sdkVersions(): { agentSdk?: string; claudeCode?: string } {
  try {
    // The SDK's exports map does not expose package.json, so read it from the app's node_modules (inside the asar
    // when packaged; Electron's fs reads through it).
    const file = join(app.getAppPath(), 'node_modules', '@anthropic-ai', 'claude-agent-sdk', 'package.json')
    const pkg = JSON.parse(readFileSync(file, 'utf8')) as { version?: string; claudeCodeVersion?: string }
    return { agentSdk: pkg.version, claudeCode: pkg.claudeCodeVersion }
  } catch {
    return {}
  }
}

let notices: ThirdPartyNotice[] | undefined

/** Packages shipped with the app (resources/third-party-notices.json, generated by build/third-party.cjs). */
export function thirdPartyNotices(): ThirdPartyNotice[] {
  notices ??= JSON.parse(readFileSync(noticesPath, 'utf8')) as ThirdPartyNotice[]
  return notices
}
