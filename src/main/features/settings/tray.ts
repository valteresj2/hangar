import appIconPath from '../../../../resources/icon.png?asset&asarUnpack'
import trayPath from '../../../../resources/tray.png?asset&asarUnpack'
import tray15Path from '../../../../resources/tray@1.5x.png?asset&asarUnpack'
import tray2Path from '../../../../resources/tray@2x.png?asset&asarUnpack'
import trayTemplatePath from '../../../../resources/trayTemplate.png?asset&asarUnpack'
import trayTemplate2Path from '../../../../resources/trayTemplate@2x.png?asset&asarUnpack'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
